using BepInEx.Bootstrap;
using UnityEngine;
using Hip=MainGirlHipHijack.Plugin;
using Map=MainGameBlankMapAdd.Plugin;

int checks=0;
void Check(bool condition,string message){if(!condition)throw new Exception(message);checks++;Console.WriteLine("PASS "+message);}
string directory=Path.Combine(AppContext.BaseDirectory,"runs",Guid.NewGuid().ToString("N"));
string file=Path.Combine(directory,"MainGirlHipHijack.log");
var actor=new ChaControl();
var map=new Map(actor);
Chainloader.PluginInfos["com.kks.maingameblankmapadd"]=new PluginInfo{Instance=map};
var hip=new Hip(actor,directory);
Action<ChaControl,long,string,string> brokenObserver=(_,_,_,_)=>throw new Exception("observer failure");
Map.HLocationMoving+=brokenObserver;map.Move();Map.HLocationMoving-=brokenObserver;
Check(actor.transform.position.x==100,"failing diagnostic subscriber cannot prevent map placement");
hip.SetDiagnostic(false);map.Move();hip.Write("off");hip.Solve();hip.Late();
Check(!Directory.Exists(directory)&&Transform.Reads==0&&map.Subscribers==0,"OFF creates no files, subscriptions or transform captures");
hip.SetDiagnostic(true);
Check(map.Subscribers==1,"ON subscribes to map events once");
hip.Start();Check(map.Subscribers==1,"repeated setup does not duplicate subscriptions");
map.Move();hip.Write("preset-load");hip.Write("gauge-blend");hip.UseOtherBinding();
Check(hip.SolverSubscribers==1,"move arms solver observer");
hip.Solve();hip.Solve();hip.Solve();
var text=File.ReadAllText(file);
Check(text.Contains("before-move")&&text.Contains("after-move")&&text.Contains("after-solver-3"),"captures before, after and three solver results");
Check(text.Contains("action=recall")&&text.Contains("place=room201")&&text.Contains("op="),"correlates action, place and operation");
Check(text.Contains("write=preset-load")&&text.Contains("write=gauge-blend")&&text.Contains("context=world"),"records writer and coordinate context");
Check(text.Contains("bindingIsProxy=False")&&text.Contains("other-target")&&text.Contains("underFemale=True"),"distinguishes different solver binding from correctly parented proxy");
long length=new FileInfo(file).Length;
hip.Solve();hip.Write("after-limit");hip.Late();
Check(new FileInfo(file).Length==length&&hip.SolverSubscribers==0,"trace stops after three solves");
hip.LoadPreset();
Check(File.ReadAllText(file).Contains("event=preset-load"),"discrete preset reload remains visible after movement window ends");
map.Move("save");hip.Late();hip.Late();hip.Late();
Check(hip.SolverSubscribers==0,"native callback fallback releases observer if solver never runs");
map.Move("edit");hip.SetDiagnostic(false);
length=new FileInfo(file).Length;int reads=Transform.Reads;
map.Move();hip.Solve();hip.Write("disabled-mid-trace");hip.LoadPreset();hip.Late();
Check(new FileInfo(file).Length==length&&Transform.Reads==reads&&hip.SolverSubscribers==0&&map.Subscribers==0,"OFF mid-trace stops output, captures and both subscriptions");
hip.SetDiagnostic(true);map.Move("restore");hip.Stop();
length=new FileInfo(file).Length;hip.Solve();map.Move();
Check(new FileInfo(file).Length==length&&hip.SolverSubscribers==0&&map.Subscribers==0,"session stop cancels old observations");
hip.Start();map.Move();hip.Solve();
Check(new FileInfo(file).Length>length,"next session can start a fresh trace");
hip.Stop();hip.SetDiagnostic(false);
Check(MainGameLogRelay.LogRelayApi.Writes==0,"dedicated diagnostics work without common relay output");
var fallback=new BepInEx.Logging.ManualLogSource();
var logger=new MainGirlHipHijack.Services.HipHijackLogger(directory,"hip","hip","hip","input","input",fallback,()=>false,()=>true);
length=new FileInfo(file).Length;
logger.Info("off");logger.Warn("off");logger.Error("off");logger.Debug("off");logger.DiagnosticInfo("off");
Check(fallback.Writes==0&&new FileInfo(file).Length==length,"disabled logger does not write or fall back to console");
Console.WriteLine($"Passed {checks} diagnostic lifecycle checks; simulated Unity boundary, no game operation.");
