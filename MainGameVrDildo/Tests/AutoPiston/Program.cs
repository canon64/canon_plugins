using System;
using MainGameVrDildo;
using UnityEngine;
using Capture = MainGameUiInputCapture.UiInputCaptureApi;
using Gate = CanonPlugins.Shared.PluginSessionGate;

static class Program
{
    static int checks;
    static void Check(bool result,string text)
    { if(!result)throw new Exception(text);checks++;Console.WriteLine("PASS "+text); }
    static bool Near(float a,float b)=>Math.Abs(a-b)<0.00001f;
    static void Same(Vector3 a,Vector3 b,string text)=>Check(Near(a.x,b.x)&&Near(a.y,b.y)&&Near(a.z,b.z),text);
    static void Main()
    {
        Console.WriteLine("Auto piston production-code boundary tests (native Unity/KKS not running)");
        float speed=1,stroke=5;
        for(int i=0;i<10;i++)PistonPolicy.Wheel(-1,false,ref speed,ref stroke);
        Check(speed==0&&stroke==5,"wheel can reach exactly zero without changing width");
        PistonPolicy.Wheel(-100,false,ref speed,ref stroke);Check(speed==0,"speed lower clamp");
        PistonPolicy.Wheel(100,false,ref speed,ref stroke);Check(speed==5,"speed upper clamp");
        PistonPolicy.Wheel(100,true,ref speed,ref stroke);Check(speed==5&&stroke==20,"Ctrl modifier changes only width");
        PistonPolicy.Wheel(-100,true,ref speed,ref stroke);Check(stroke==0,"width lower clamp");
        Check(PistonPolicy.Speed(float.NaN)==0&&PistonPolicy.Stroke(float.PositiveInfinity)==5,"invalid settings use stopped defaults");
        speed=1;stroke=5;
        PistonPolicy.Stick(.25f,-.25f,.05f,ref speed,ref stroke);Check(speed==1&&stroke==5,"stick deadzone");
        PistonPolicy.Stick(1,.8f,.05f,ref speed,ref stroke);Check(Near(speed,1.05f)&&Near(stroke,5),"right changes only speed");
        PistonPolicy.Stick(1,1,.05f,ref speed,ref stroke);Check(Near(speed,1.05f)&&Near(stroke,5.25f),"vertical dominant tie changes only width");
        PistonPolicy.Stick(-1,0,.05f,ref speed,ref stroke);Check(Near(speed,1)&&Near(stroke,5.25f),"left slows down");
        PistonPolicy.Stick(0,-1,.05f,ref speed,ref stroke);Check(Near(speed,1)&&Near(stroke,5),"down narrows stroke");
        var p=new Plugin();Check(!p.Enabled,"spawn starts OFF");
        Gate.Allowed=false;p.Enable(true);Check(!p.Enabled,"gate denial rejects start");
        Gate.Allowed=true;Application.isFocused=false;p.Enable(true);Check(!p.Enabled,"unfocused start rejected");
        Application.isFocused=true;p.Enable(true);Check(p.Enabled&&p.Driving,"positive speed automatically starts native animation");
        Check(p.Animation.Clip.legacy&&p.Animation.Clip.wrapMode==WrapMode.Loop&&p.Animation.cullingType==AnimationCullingType.AlwaysAnimate,"legacy looping animation remains active offscreen");
        var curve=p.Animation.Clip.Curve;
        Check(Near(curve.Evaluate(.25f)-curve.Evaluate(.75f),.05f),"5cm is full end-to-end width");
        Check(Near(curve.Evaluate(0),curve.Evaluate(1)),"loop ends join without discontinuity");
        p.Animation.Advance(.23f);float phase=p.State.normalizedTime;Vector3 held=p.Motion.position;
        p.Edit(0,5);p.Animation.Advance(5);
        Check(!p.Enabled&&!p.Animation.enabled&&!p.Driving&&Near(p.State.normalizedTime,phase),"speed zero automatically turns OFF while retaining phase");
        Same(held,p.Motion.position,"speed zero freezes visible position");
        p.Edit(0,10);Check(Near(p.State.normalizedTime,phase),"width change preserves phase at zero speed");
        Same(held,p.Motion.position,"width change preserves frozen position");
        p.Edit(2,10);p.Animation.Advance(.1f);Check(Near(p.State.normalizedTime,phase+.2f),"resume advances from held phase at new speed");
        Vector3 beforeBase=p._model.transform.position;
        p.Animation.Advance(.1f);Same(beforeBase,p._model.transform.position,"native piston never overwrites hand/gizmo/Composer base");
        var parent=new Transform { position=new Vector3(3,2,1),localScale=new Vector3(2,2,2),rotation=Quaternion.RotateZ(.7f) };
        phase=p.State.normalizedTime;
        Check(Plugin.TrySetComposerParent(parent,false),"Composer can attach while piston active");
        held=p.Motion.position;
        Check(p.Enabled&&Near(p.State.normalizedTime,phase),"Composer attachment preserves active phase");
        curve=p.Animation.Clip.Curve;
        Check(Near((curve.Evaluate(.25f)-curve.Evaluate(.75f))*p._model.transform.lossyScale.y,.1f),"world stroke compensates parent scale");
        Vector3 shift=new Vector3(1,2,3);parent.position+=shift;
        Same(held+shift,p.Motion.position,"Composer movement carries piston without accumulating offsets");
        p._grabController=new Controller();p._grabController.transform.position=new Vector3(9,8,7);
        p._model.transform.SetParent(p._grabController.transform,true);
        p._desktopGizmoProxy=new GameObject();held=p.Motion.position;
        p.Enable(false);Same(held,p.Motion.position,"OFF bakes visible world offset under rotated scaled parent");
        Same(p._model.transform.position,p._desktopGizmoProxy.transform.position,"OFF updates gizmo base");
        Check(p._model.transform.parent==p._grabController.transform,"OFF preserves native hand parenting");
        Check(!p.Animation.enabled&&p.State==null,"OFF stops native driver and removes clip");
        p.Enable(false);Same(held,p.Motion.position,"repeat OFF is idempotent");
        p.Enable(true);Same(held,p.Motion.position,"next ON starts at visible position");
        Capture.Wheel=1;Capture.Right=false;speed=p._settings.PistonSpeed;stroke=p._settings.PistonStrokeCm;
        p.Wheel();Check(Near(p._settings.PistonSpeed,speed+.1f)&&p._settings.PistonStrokeCm==stroke,"desktop wheel routes speed");
        Input.LeftControl=true;speed=p._settings.PistonSpeed;p.Wheel();Check(p._settings.PistonSpeed==speed&&Near(p._settings.PistonStrokeCm,stroke+.5f),"left Ctrl plus left wheel routes only width");
        Input.LeftControl=false;Input.RightControl=true;stroke=p._settings.PistonStrokeCm;
        p.Wheel();Check(p._settings.PistonSpeed==speed&&Near(p._settings.PistonStrokeCm,stroke+.5f),"right Ctrl plus left wheel routes only width");
        Input.RightControl=false;Capture.Right=true;stroke=p._settings.PistonStrokeCm;
        p.Wheel();Check(Near(p._settings.PistonSpeed,speed+.1f)&&p._settings.PistonStrokeCm==stroke,"right mouse no longer selects width");
        Input.LeftControl=true;
        Check(Capture.LastOwner=="gizmo.gizmo.17","wheel uses actual gizmo capture owner");
        Capture.Blocked=true;stroke=p._settings.PistonStrokeCm;p.Wheel();Check(stroke==p._settings.PistonStrokeCm,"other UI blocks piston wheel input");
        Capture.Blocked=false;Capture.Left=false;p.Wheel();Check(stroke==p._settings.PistonStrokeCm,"wheel without left hold has no effect");
        Application.isFocused=false;p.Stick(1,0);Check(stroke==p._settings.PistonStrokeCm,"unfocused stick has no effect");
        Application.isFocused=true;Gate.Allowed=false;p.Enable(false);Check(!p.Enabled,"cleanup remains possible after gate invalidation");
        Gate.Allowed=true;p.Enable(true);p._settings.Enabled=false;p.Edit(1,5);Check(!p.Enabled,"disabling settings stops piston");
        p._settings.Enabled=true;p.Enable(true);p.Animation.Advance(.3f);held=p.Motion.position;
        speed=p._settings.PistonSpeed;phase=p.State.normalizedTime;
        p._grabController=new Controller();p.Focus(false);
        Check(p.Enabled&&p.Animation.enabled&&p._grabController==null&&p._desktopGizmo==null,"focus loss releases interaction without stopping piston");
        Check(p._settings.PistonSpeed==speed&&Near(p.State.normalizedTime,phase),"focus loss preserves speed and animation phase");
        Same(held,p.Motion.position,"focus loss preserves visible pose");
        p.Animation.Advance(.1f);Check(p.State.normalizedTime>phase,"animation remains enabled while unfocused");
        p.Focus(true);Check(p.Enabled&&p._settings.PistonSpeed==speed,"focus return preserves running piston speed");
        p.Enable(true);p._grabController=new Controller();p.Disable();
        Check(!p.Enabled&&!p.Animation.enabled&&p._grabController==null,"actual OnDisable stops animation and releases grip");
        var q=new Plugin();Capture.Blocked=false;Capture.Left=true;Capture.Right=false;Capture.Wheel=1;Input.LeftControl=true;
        q.Wheel();Check(!q.Enabled&&q._settings.PistonSpeed==0&&Near(q._settings.PistonStrokeCm,5.5f),"width wheel while stopped never starts piston");
        Input.LeftControl=false;q.Wheel();Check(q.Enabled&&Near(q._settings.PistonSpeed,.1f),"first left-drag wheel up starts piston without ON button");
        q.Animation.Advance(.7f);held=q.Motion.position;phase=q.State.normalizedTime;
        Capture.Wheel=-1;q.Wheel();Check(!q.Enabled&&q._settings.PistonSpeed==0,"left-drag wheel down to zero automatically turns OFF");
        Same(held,q.Motion.position,"automatic OFF freezes current visible position");
        Capture.Wheel=1;q.Wheel();Check(q.Enabled&&Near(q.State.normalizedTime,phase),"next wheel up automatically resumes held phase");
        q._desktopGizmo.IsDragging=false;speed=q._settings.PistonSpeed;q.Wheel();
        Check(q._settings.PistonSpeed==speed,"left held outside actual gizmo grab cannot change speed");
        q._desktopGizmo.IsDragging=true;
        q.SyncRhythm(true);q.Rhythm(false,0,0);Check(q.Driving,"music sync without music falls back to manual speed");
        q.Wheel();Check(q._settings.PistonRhythmSync&&q.Driving&&Near(q.State.speed,q._settings.PistonSpeed),"held wheel sets manual fallback speed without disabling sync");
        q.Rhythm(false,0,0);Check(q.Driving,"later stopped music signal keeps manual piston moving");
        q.SyncRhythm(true);q.Rhythm(true,0,2);Input.LeftControl=true;q.Wheel();
        Check(q._settings.PistonRhythmSync&&Near(q.State.speed,2),"Ctrl width wheel preserves requested music sync");
        Input.LeftControl=false;q.SyncRhythm(false);
        q.Edit(0,q._settings.PistonStrokeCm);q.Stick(0,1);Check(!q.Enabled,"vertical stick while stopped changes width only");
        q.Stick(1,0);Check(q.Enabled&&q._settings.PistonSpeed>0,"right stick sets positive speed");
        q.Stick(-1,0);Check(!q.Enabled&&q._settings.PistonSpeed==0,"left stick reaches zero speed");
        phase=q.State.normalizedTime;
        q.Focus(false);q.Focus(true);Check(!q.Enabled&&q.State!=null&&Near(q.State.normalizedTime,phase),"focus changes preserve zero-speed stop and resumable phase");
        var r=new Plugin();r.Enable(true);r.SyncRhythm(true);
        Check(Near(r.State.speed,1)&&r.Driving,"sync without music uses configured speed");
        r.Rhythm(true,2.25,2);Check(Near(r.State.speed,2)&&Near(r.State.normalizedTime,.25f)&&r.Driving,"sync applies cycle rate and phase");
        r.Edit(3,8);Check(Near(r.State.speed,2)&&r._settings.PistonSpeed==3,"manual speed stays stored while sync owns playback");
        r.Rhythm(true,9.75,1);Check(Near(r.State.normalizedTime,.75f)&&Near(r.State.speed,1),"seek and intensity change update phase and frequency");
        phase=r.State.normalizedTime;held=r.Motion.position;
        r.Rhythm(false,0,0);Check(Near(r.State.speed,3)&&r.Driving,"music stop falls back to configured manual speed");
        Check(Near(r.State.normalizedTime,phase),"music stop preserves phase");
        Same(held,r.Motion.position,"music stop fallback preserves shaft position");
        r.Rhythm(true,10,1);Check(r.Driving,"music restart resumes synchronization");
        r.SyncRhythm(false);Check(Near(r.State.speed,3),"sync OFF restores stored manual speed");
        phase=r.State.normalizedTime;r.Rhythm(true,20.5,2);
        Check(Near(r.State.speed,3)&&Near(r.State.normalizedTime,phase),"disabled sync ignores rhythm changes");
        r.Edit(0,8);r.SyncRhythm(true);r.Rhythm(true,21,2);
        Check(!r.Enabled&&!r.Animation.enabled,"speed zero cannot be restarted by rhythm events");
        r.Edit(1,8);r.Rhythm(true,0,6);Check(r.State.speed==0,"out of range rhythm speed pauses instead of losing sync");
        r.Rhythm(true,double.NaN,2);Check(r.State.speed==0,"invalid rhythm phase is rejected");
        r.Rhythm(true,0,double.PositiveInfinity);Check(r.State.speed==0,"invalid rhythm speed is rejected");
        r.Rhythm(true,0,2);Gate.Allowed=false;phase=r.State.normalizedTime;r.Rhythm(true,4.5,3);
        Check(Near(r.State.speed,2)&&Near(r.State.normalizedTime,phase),"denied gate prevents applying rhythm data");
        Gate.Allowed=true;r.isActiveAndEnabled=false;r.Rhythm(true,4.5,3);
        Check(Near(r.State.speed,2),"disabled component rejects rhythm changes");
        r.isActiveAndEnabled=true;r.Disable();r.Rhythm(true,8.5,3);
        Check(!r.Enabled&&!r.Animation.enabled,"late rhythm signal cannot restart disabled motion");
        int signals=0;double receivedPhase=0;
        MainGameRhythmSync.MotionSyncApi.Publish(false);
        var subscription=MainGameRhythmSync.MotionSyncApi.Subscribe((active,p0,hz)=>{signals++;receivedPhase=p0;r.Rhythm(active,p0,hz);});
        Check(signals==1,"subscription receives current stopped state");
        Time.time=0;MainGameRhythmSync.MotionSyncApi.Publish(true,0,2);
        Check(signals==2,"clock start publishes motion signal");
        Time.time=1;MainGameRhythmSync.MotionSyncApi.Publish(true,2,2);
        Check(signals==2,"continuous native playback needs no repeated signal");
        MainGameRhythmSync.MotionSyncApi.Publish(true,5,2);
        Check(signals==3&&receivedPhase==5,"clock seek publishes correction");
        MainGameRhythmSync.MotionSyncApi.Publish(true,5,1);
        Check(signals==4,"frequency change publishes correction");
        Time.time=2;double snapshot=0;
        var second=MainGameRhythmSync.MotionSyncApi.Subscribe((a,p0,hz)=>snapshot=p0);
        Check(snapshot==6,"new subscriber receives extrapolated clock phase");
        second.Dispose();subscription.Dispose();subscription.Dispose();
        MainGameRhythmSync.MotionSyncApi.Publish(false);
        Check(signals==4,"disposing subscription removes callbacks idempotently");
        var heldVr=new Plugin();VRGIN.Core.VR.Active=true;heldVr._grabController=new Controller();
        heldVr.Stick(1,0);Check(!heldVr.Enabled&&heldVr._settings.PistonSpeed>0,"VR speed adjustment cannot run without trigger");
        heldVr.Edit(0,5);heldVr.SyncRhythm(true);heldVr.Rhythm(false,0,0);heldVr.TriggerPress();
        Check(heldVr.Enabled&&Near(heldVr._settings.PistonSpeed,1),"first held trigger starts at one cycle per second from zero");
        Check(heldVr.Driving&&heldVr._settings.PistonRhythmSync,"VR start uses manual fallback and retains sync preference");
        heldVr.Animation.Advance(.31f);var basePosition=heldVr._model.transform.position;held=heldVr.Motion.position;phase=heldVr.State.normalizedTime;
        heldVr.TriggerPress();Check(!heldVr.Enabled&&!heldVr.Animation.enabled&&Near(heldVr._settings.PistonSpeed,1),"second trigger press pauses and retains speed");
        Same(basePosition,heldVr._model.transform.position,"toggle stop never bakes offset into item base");
        Same(held,heldVr.Motion.position,"toggle stop retains visible shaft position");
        Check(Near(heldVr.State.normalizedTime,phase),"toggle stop retains phase");
        heldVr.Rhythm(true,9,2);Check(!heldVr.Enabled&&!heldVr.Animation.enabled,"rhythm update cannot restart trigger-paused piston");
        heldVr.Rhythm(false,0,0);
        heldVr.TriggerPress();Check(heldVr.Enabled&&Near(heldVr.State.normalizedTime,phase),"next trigger press resumes phase");
        Same(held,heldVr.Motion.position,"fresh trigger has no position jump");
        heldVr.TriggerPress();heldVr.Stick(0,1);Check(!heldVr.Enabled,"changing stroke while paused never starts piston");
        heldVr.TriggerPress();Check(heldVr.Enabled,"stroke edit can resume on next trigger");
        speed=heldVr._settings.PistonSpeed;Capture.Wheel=1;heldVr.Wheel();
        Check(heldVr._settings.PistonSpeed==speed,"desktop wheel cannot control VR piston");
        heldVr._grabController=null;phase=heldVr.State.normalizedTime;heldVr.Animation.Advance(.1f);
        Check(heldVr.Driving&&heldVr.State.normalizedTime>phase,"unheld VR piston keeps advancing");
        Application.isFocused=false;heldVr.Edit(2,9);
        Check(heldVr.Driving&&Near(heldVr.State.speed,2),"unheld VR piston settings retain trigger running state");
        heldVr.Edit(0,9);heldVr.Edit(1,9);
        Check(heldVr.Driving,"unheld running state resumes from zero speed without desktop focus");
        heldVr.TriggerPress();Check(!heldVr.Enabled,"trigger can stop previously unheld piston");
        heldVr.Disable();Check(heldVr._settings.PistonSpeed==0,"disable clears persistent VR speed");
        Application.isFocused=true;
        VRGIN.Core.VR.Active=false;
        Console.WriteLine($"PASS {checks} checks; live animation, input capture and KKS reactions remain unverified");
    }
}
